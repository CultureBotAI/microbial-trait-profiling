@dataclass(frozen=True)
class ScenarioRun:
    """Every replicate's outcomes for one scenario, and its realised injections."""

    runs: list[list[Outcome]]
    injections: list[InjectionEffect]


def run_replicates(
    profiles: Sequence[Profile],
    scenario: Scenario,
    replicates: int,
    seed: int = SEED,
    procedures: Mapping[str, Procedure] | None = None,
) -> ScenarioRun:
    """Run every procedure on ``replicates`` transformed copies of the corpus."""
    chosen = procedures or {}
    runs: list[list[Outcome]] = []
    injections: list[InjectionEffect] = []
    for index in range(replicates):
        rng = replicate_rng(seed, scenario.name, index)
        resample = scenario.transform(profiles, rng)
        if resample.injection is not None:
            injections.append(resample.injection)
        outcomes: list[Outcome] = []
        for procedure in chosen.values():
            outcomes.extend(procedure(resample.profiles))
        runs.append(outcomes)
    return ScenarioRun(runs, injections)


def _interval(successes: int, trials: int) -> tuple[float, float]:
    if not trials:
        return (0.0, 1.0)
    interval = binomtest(successes, trials).proportion_ci(confidence_level=0.95, method="exact")
    return float(interval.low), float(interval.high)


def _upper_bound(successes: int, trials: int) -> float | None:
    """The one-sided exact 95% upper bound, from the two-sided 90% Clopper-Pearson."""
    if not trials:
        return None
    interval = binomtest(successes, trials).proportion_ci(confidence_level=0.90, method="exact")
    return float(interval.high)


def attainable_p_at_alpha(scored: int, alpha: float = ALPHA) -> tuple[float | None, float | None]:
    """The two attainable two-sided exact-binomial p-values straddling ``alpha``.

    These tests are discrete, so their p-values are a finite set and the decision at
    ``alpha`` is as coarse as the gap between the neighbouring attainable values.
    The p-value rises monotonically as the success count approaches ``scored / 2``,
    so a bisection finds the pair in a handful of evaluations.
    """
    if scored <= 0:
        return (None, None)

    def p_at(successes: int) -> float:
        return float(binomtest(successes, scored, p=0.5).pvalue)

    half = scored // 2
    if p_at(0) > alpha:
        return (None, p_at(0))
    low, high = 0, half
    while low < high:
        middle = (low + high + 1) // 2
        if p_at(middle) <= alpha:
            low = middle
        else:
            high = middle - 1
    below = p_at(low)
    above = p_at(low + 1) if low < half else None
    return (below, above)


def _is_injected(label: object, injected: str | None) -> bool:
    """A ratio naming the injected trait carries the injected effect too."""
    return injected is not None and injected in str(label).split("/")


def summarize(
    runs: Sequence[Sequence[Outcome]], scenario: Scenario, injected: str | None
) -> list[dict[str, object]]:
    """Per-test rejection rates, family error, and false-discovery proportions."""
    rows: list[dict[str, object]] = []
    procedures = sorted({o.procedure for run in runs for o in run})
    for procedure in procedures:
        labels = sorted({o.label for run in runs for o in run if o.procedure == procedure})
        for label in labels:
            tested = [
                next(
                    (o for o in run if o.procedure == procedure and o.label == label),
                    None,
                )
                for run in runs
            ]
            present = [o for o in tested if o is not None and o.selected and o.p_value is not None]
            rejected_p = sum(1 for o in present if o.p_value is not None and o.p_value <= ALPHA)
            rejected_q = sum(
                1 for o in present if o.q_value is not None and o.q_value <= Q_THRESHOLD
            )
            low, high = _interval(rejected_p, len(present))
            q_low, q_high = _interval(rejected_q, len(present))
            scored = [o.scored for o in present if o.scored is not None]
            median_scored = int(median(scored)) if scored else None
            below, above = attainable_p_at_alpha(median_scored) if median_scored else (None, None)
            rows.append(
                {
                    "scenario": scenario.name,
                    "truth": scenario.truth,
                    "procedure": procedure,
                    "label": label,
                    "role": "injected_effect" if _is_injected(label, injected) else "null",
                    "replicates": len(runs),
                    "replicates_tested": len(present),
                    "rejections_p": rejected_p,
                    "rejection_rate_p": rejected_p / len(present) if present else None,
                    "rejection_rate_p_ci_low": low,
                    "rejection_rate_p_ci_high": high,
                    "rejections_q": rejected_q,
                    "rejection_rate_q": rejected_q / len(present) if present else None,
                    "rejection_rate_q_ci_low": q_low,
                    "rejection_rate_q_ci_high": q_high,
                    "median_scored_units": median_scored,
                    "smallest_observed_p": min(
                        (o.p_value for o in present if o.p_value is not None), default=None
                    ),
                    "attainable_p_below_alpha": below,
                    "attainable_p_above_alpha": above,
                }
            )
    for procedure in procedures:
        any_rejection = 0
        false_discovery: list[float] = []
        for run in runs:
            calls = [
                o
                for o in run
                if o.procedure == procedure
                and o.selected
                and o.q_value is not None
                and o.q_value <= Q_THRESHOLD
            ]
            any_rejection += bool(calls)
            if calls:
                false = [o for o in calls if not _is_injected(o.label, injected)]
                false_discovery.append(len(false) / len(calls))
            else:
                false_discovery.append(0.0)
        low, high = _interval(any_rejection, len(runs))
        rows.append(
            {
                "scenario": scenario.name,
                "truth": scenario.truth,
                "procedure": procedure,
                "label": "FAMILY",
                "role": "family",
                "replicates": len(runs),
                "replicates_tested": len(runs),
                "rejections_p": any_rejection,
                "rejection_rate_p": any_rejection / len(runs) if runs else None,
                "rejection_rate_p_ci_low": low,
                "rejection_rate_p_ci_high": high,
                "rejections_q": any_rejection,
                "rejection_rate_q": any_rejection / len(runs) if runs else None,
                "rejection_rate_q_ci_low": low,
                "rejection_rate_q_ci_high": high,
                "mean_false_discovery_proportion": (
                    sum(false_discovery) / len(false_discovery) if false_discovery else None
                ),
            }
        )
    return rows


def replicate_counts(
    runs: Sequence[Sequence[Outcome]], scenario: Scenario, injected: str | None
) -> list[dict[str, object]]:
    """One row per procedure and replicate: the independent unit of every criterion.

    Labels tested inside one replicate share that replicate's resampled corpus, so
    pooling them as independent Bernoulli trials understates the uncertainty. This
    ledger keeps the cluster structure, and the criteria read it rather than the
    per-label summary.
    """
    rows: list[dict[str, object]] = []
    procedures = sorted({o.procedure for run in runs for o in run})
    for procedure in procedures:
        for index, run in enumerate(runs):
            mine = [o for o in run if o.procedure == procedure and o.selected]
            tested = [o for o in mine if o.p_value is not None]
            null_tested = [o for o in tested if not _is_injected(o.label, injected)]
            rows.append(
                {
                    "scenario": scenario.name,
                    "procedure": procedure,
                    "replicate": index,
                    "tests_evaluated": len(tested),
                    "null_tests_evaluated": len(null_tested),
                    "null_tests_rejected_p": sum(
                        1 for o in null_tested if o.p_value is not None and o.p_value <= ALPHA
                    ),
                    "family_rejected_q": int(
                        any(o.q_value is not None and o.q_value <= Q_THRESHOLD for o in mine)
                    ),
                }
            )
    return rows


def summarize_injection(
    effects: Sequence[InjectionEffect], scenario: Scenario
) -> list[dict[str, object]]:
    """The effective injection size, averaged over the replicates that applied it."""
    if not effects:
        return []
    eligible = [e.eligible_profiles for e in effects]
    changed = [e.changed_profiles for e in effects]
    realized = [e.mean_realized_multiplier for e in effects if e.mean_realized_multiplier]
    when_changed = [
        e.mean_realized_multiplier_when_changed
        for e in effects
        if e.mean_realized_multiplier_when_changed
    ]
    return [
        {
            "scenario": scenario.name,
            "trait": effects[0].trait,
            "replicates": len(effects),
            "nominal_multiplier": effects[0].nominal_multiplier,
            "mean_eligible_profiles": fmean(eligible),
            "mean_changed_profiles": fmean(changed),
            "share_unchanged_after_rounding": (
                1.0 - fmean(changed) / fmean(eligible) if fmean(eligible) else None
            ),
            "mean_capped_profiles": fmean([e.capped_profiles for e in effects]),
            "mean_effective_multiplier": fmean(realized) if realized else None,
            "mean_effective_multiplier_when_changed": (
                fmean(when_changed) if when_changed else None
            ),
        }
    ]


@dataclass(frozen=True)
class PooledRate:
    """A rejection rate pooled over labels, with the replicate as the cluster."""

    clusters: int
    trials: int
    rejections: int
    rate: float
    standard_error: float
    upper_bound: float
    design_effect: float


def pooled_rate(counts: Sequence[tuple[int, int]]) -> PooledRate | None:
    """Pool each replicate's (rejections, tests) into one rate with a clustered bound.

    This is the ratio estimator over replicate clusters. Its variance reduces to the
    binomial one when every replicate contributes a single test, and inflates it by
    the measured design effect when a replicate contributes several correlated tests.
    """
    usable = [(k, m) for k, m in counts if m > 0]
    if len(usable) < 2:
        return None
    rejections = sum(k for k, _ in usable)
    trials = sum(m for _, m in usable)
    clusters = len(usable)
    rate = rejections / trials
    residual = math.fsum((k - rate * m) ** 2 for k, m in usable)
    variance = clusters / (clusters - 1) * residual / trials**2
    independent = rate * (1.0 - rate) / trials
    error = math.sqrt(variance)
    return PooledRate(
        clusters=clusters,
        trials=trials,
        rejections=rejections,
        rate=rate,
        standard_error=error,
        upper_bound=rate + Z_ONE_SIDED * error,
        design_effect=variance / independent if independent > 0 and variance > 0 else 1.0,
    )


def criterion_pass_probability(
    rate: float, trials: int, tolerance: float, design_effect: float = 1.0
) -> float:
    """Probability the amended criterion passes when the true per-test rate is ``rate``.

    The decision rule is ``rate_hat + z * se <= tolerance``, so this is the
    probability that a design with this many trials and this design effect produces
    an estimate low enough to clear it. Reported beside every verdict: a pass that
    a 0.08 procedure would also have obtained is not evidence of anything.
    """
    if trials <= 0:
        return 1.0
    error = math.sqrt(rate * (1.0 - rate) * design_effect / trials)
    if error <= 0.0:
        return 1.0 if rate <= tolerance else 0.0
    return float(norm.cdf((tolerance - Z_ONE_SIDED * error - rate) / error))


def _operating_column_names() -> list[str]:
    """The operating-characteristic column of each declared true rate, in order."""
    names = []
    for point in OPERATING_POINTS:
        key = f"{point:.3f}".replace(".", "_")
        prefix = "pass_probability_at_" if point <= ALPHA else "fail_probability_at_"
        names.append(prefix + key)
    return names


def _operating_columns(
    trials: int, tolerance: float, design_effect: float = 1.0
) -> dict[str, object]:
    """Pass probability at the nominal level, fail probability at inflated rates."""
    columns: dict[str, object] = {}
    for point, name in zip(OPERATING_POINTS, _operating_column_names(), strict=True):
        passes = criterion_pass_probability(point, trials, tolerance, design_effect)
        columns[name] = passes if point <= ALPHA else 1.0 - passes
    return columns


def _criterion_row(
    criterion_id: str,
    procedure: str,
    requirement: str,
    verdict: str,
    detail: str,
    expected: str | None,
    extra: Mapping[str, object] | None = None,
) -> dict[str, object]:
    row: dict[str, object] = {
        "criterion": criterion_id,
        "procedure": procedure,
        "requirement": requirement,
        "verdict": verdict,
        "expected_verdict": expected,
        "expectation_met": None if expected is None else expected == verdict,
        "estimate": None,
        "upper_bound": None,
        "tolerance": None,
        "clusters": None,
        "trials": None,
        "rejections": None,
        "design_effect": None,
    }
    for name in _operating_column_names():
        row[name] = None
    row.update(extra or {})
    row["detail"] = detail
    return row


def _per_test_verdict(
    criterion: Mapping[str, Any], procedure: str, ledger: Sequence[Mapping[str, object]]
) -> dict[str, object]:
    tolerance = float(criterion["tolerance"])
    expected = dict(criterion.get("expected_verdict", {})).get(procedure)
    counts = [
        (int(str(r["null_tests_rejected_p"])), int(str(r["null_tests_evaluated"])))
        for r in ledger
        if r["procedure"] == procedure and str(r["scenario"]).startswith("complete_null")
    ]
    pooled = pooled_rate(counts)
    if pooled is None:
        return _criterion_row(
            str(criterion["id"]),
            procedure,
            str(criterion["criterion"]),
            "not_evaluated",
            "no complete-null replicates recorded for this procedure",
            expected,
            {"tolerance": tolerance},
        )
    verdict = "pass" if pooled.upper_bound <= tolerance else "fail"
    detail = (
        f"pooled per-test rejection rate {pooled.rate:.4f} "
        f"({pooled.rejections}/{pooled.trials} over {pooled.clusters} replicate clusters), "
        f"one-sided 95% upper bound {pooled.upper_bound:.4f} "
        f"{'<=' if verdict == 'pass' else '>'} tolerance {tolerance:.3f}"
    )
    return _criterion_row(
        str(criterion["id"]),
        procedure,
        str(criterion["criterion"]),
        verdict,
        detail,
        expected,
        {
            "estimate": pooled.rate,
            "upper_bound": pooled.upper_bound,
            "tolerance": tolerance,
            "clusters": pooled.clusters,
            "trials": pooled.trials,
            "rejections": pooled.rejections,
            "design_effect": pooled.design_effect,
            **_operating_columns(pooled.trials, tolerance, pooled.design_effect),
        },
    )


def _family_verdict(
    criterion: Mapping[str, Any], procedure: str, ledger: Sequence[Mapping[str, object]]
) -> dict[str, object]:
    tolerance = float(criterion["tolerance"])
    expected = dict(criterion.get("expected_verdict", {})).get(procedure)
    flags = [
        int(str(r["family_rejected_q"]))
        for r in ledger
        if r["procedure"] == procedure and str(r["scenario"]).startswith("complete_null")
    ]
    if not flags:
        return _criterion_row(
            str(criterion["id"]),
            procedure,
            str(criterion["criterion"]),
            "not_evaluated",
            "no complete-null replicates recorded for this procedure",
            expected,
            {"tolerance": tolerance},
        )
    rejections, trials = sum(flags), len(flags)
    bound = _upper_bound(rejections, trials)
    rate = rejections / trials
    verdict = "pass" if bound is not None and bound <= tolerance else "fail"
    detail = (
        f"replicates with any q <= {Q_THRESHOLD}: {rate:.4f} ({rejections}/{trials}), "
        f"exact one-sided 95% upper bound {bound:.4f} "
        f"{'<=' if verdict == 'pass' else '>'} tolerance {tolerance:.3f}"
        if bound is not None
        else "no bound computable"
    )
    return _criterion_row(
        str(criterion["id"]),
        procedure,
        str(criterion["criterion"]),
        verdict,
        detail,
        expected,
        {
            "estimate": rate,
            "upper_bound": bound,
            "tolerance": tolerance,
            "clusters": trials,
            "trials": trials,
            "rejections": rejections,
            "design_effect": 1.0,
            **_operating_columns(trials, tolerance),
        },
    )


def _power_verdict(
    criterion: Mapping[str, Any], procedure: str, rows: Sequence[Mapping[str, object]]
) -> dict[str, object]:
    limit = float(criterion["max_interval_width"])
    expected = dict(criterion.get("expected_verdict", {})).get(procedure)
    declared = [f"injected_{m:g}x_study_flip" for m in INJECTION_MULTIPLIERS]
    powered = [r for r in rows if r["procedure"] == procedure and r["role"] == "injected_effect"]
    problems: list[str] = []
    widths: list[float] = []
    reported: list[str] = []
    for name in declared:
        here = [r for r in powered if r["scenario"] == name]
        if not here:
            problems.append(f"{name}: no injected label reported")
            continue
        for row in here:
            rate, low, high = (
                row["rejection_rate_q"],
                row["rejection_rate_q_ci_low"],
                row["rejection_rate_q_ci_high"],
            )
            if rate is None or low is None or high is None:
                problems.append(f"{name}/{row['label']}: power or its interval missing")
                continue
            width = float(str(high)) - float(str(low))
            widths.append(width)
            reported.append(
                f"{name}/{row['label']}: power {float(str(rate)):.3f} "
                f"[{float(str(low)):.3f}, {float(str(high)):.3f}]"
            )
            if width > limit:
                problems.append(
                    f"{name}/{row['label']}: interval width {width:.3f} exceeds {limit:.3f}"
                )
    verdict = "fail" if problems else "pass"
    detail = "; ".join(problems) if problems else "; ".join(reported)
    return _criterion_row(
        str(criterion["id"]),
        procedure,
        str(criterion["criterion"]),
        verdict,
        detail,
        expected,
        {
            "tolerance": limit,
            "upper_bound": max(widths) if widths else None,
            "trials": len(widths),
        },
    )


def _selection_row(
    criterion: Mapping[str, Any], procedure: str, rows: Sequence[Mapping[str, object]]
) -> dict[str, object]:
    per_test = [
        r
        for r in rows
        if r["procedure"] == procedure
        and r["role"] == "null"
        and r["label"] != "FAMILY"
        and str(r["scenario"]).startswith("complete_null")
        and r["rejection_rate_p"] is not None
    ]
    rates = [float(str(r["rejection_rate_p"])) for r in per_test]
    detail = (
        f"per-test rejection rate under the null between {min(rates):.3f} and {max(rates):.3f}"
        if rates
        else "no selected tests"
    )
    return _criterion_row(
        str(criterion["id"]),
        procedure,
        str(criterion["criterion"]),
        "reported",
        detail,
        None,
        {"estimate": fmean(rates) if rates else None},
    )


def check_criteria(
    rows: Sequence[Mapping[str, object]],
    ledger: Sequence[Mapping[str, object]] = (),
    protocol: Mapping[str, Any] | None = None,
) -> list[dict[str, object]]:
    """Judge the declared acceptance criteria, reporting failures as failures."""
    declared = dict(protocol) if protocol is not None else load_protocol()
    results: list[dict[str, object]] = []
    for criterion in declared["acceptance_criteria"]:
        for procedure in criterion["applies_to"]:
            if criterion["id"] == "per_test_level":
                results.append(_per_test_verdict(criterion, procedure, ledger))
            elif criterion["id"] == "family_error":
                results.append(_family_verdict(criterion, procedure, ledger))
            elif criterion["id"] == "power_reported":
                results.append(_power_verdict(criterion, procedure, rows))
            elif criterion["id"] == "selection_inflation_measured":
                results.append(_selection_row(criterion, procedure, rows))
            else:
                results.append(
                    _criterion_row(
                        str(criterion["id"]),
                        procedure,
                        str(criterion["criterion"]),
                        "not_evaluated",
                        "no checker implements this criterion",
                        None,
                    )
                )
    return results


def flip_assignments(
    profiles: Sequence[Profile],
    *,
    unit: str = "study",
    replicates: int = SHARED_FLIP_REPLICATES,
    seed: int = SEED,
    stream: str = "complete_null_study_flip",
) -> list[dict[str, object]]:
    """The per-replicate flip set, as a table another arm can consume (#263).

    ``stream`` is the scenario name whose replicates these are, so replicate ``i``
    here is replicate ``i`` of that scenario: an arm that reruns its own pipeline on
    these assignments is measured on the identical null, not merely a similar one.
    """
    keys = unit_keys(profiles, unit)
    rows: list[dict[str, object]] = []
    for index in range(replicates):
        rng = replicate_rng(seed, stream, index)
        flipped = flipped_units(profiles, rng, unit=unit)
        for key in keys:
            study, experiment = _unit_columns(key, unit)
            rows.append(
                {
                    "seed": seed,
                    "stream": stream,
                    "unit": unit,
                    "replicate": index,
                    "study_id": study,
                    "experiment_id": experiment,
                    "flipped": int(key in flipped),
                }
            )
    return rows


def _unit_columns(key: Hashable, unit: str) -> tuple[str, str | None]:
    """Split a resampling unit into atomic study and experiment columns."""
    if unit == "study":
        return str(key), None
    if isinstance(key, tuple) and len(key) == 2:
        return str(key[0]), str(key[1])
    raise ValueError(f"unit {unit!r} does not describe {key!r}")


def _format(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:.6g}"
    return str(value)


def _write(path: Path, rows: Sequence[Mapping[str, object]]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields: list[str] = []
    for row in rows:
        for key in row:
            if key not in fields:
                fields.append(key)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t", lineterminator="\n")
        writer.writerow(fields)
        writer.writerows([_format(row.get(field)) for field in fields] for row in rows)
    return path


