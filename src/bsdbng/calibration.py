"""Do this repository's directional tests hold their error rates? (#182)

Correct arithmetic and an agreed correction do not make a procedure calibrated. This
module measures what the directional-consistency procedures actually do when their
own nulls are true, following the protocol declared in
``methods/calibration_protocol.json``, whose amendments are disclosed there rather
than applied silently.

The null is generated by flipping directions on the real corpus rather than by
simulating counts: for a sampled half of the units, the increased and decreased
labels of every profile in that unit are exchanged. Under each procedure's null the
two sides of a pair are exchangeable, so the flip leaves the distribution unchanged;
and because the counts themselves are untouched, the annotation correlations, the
unequal experiment counts per study, the zeros, and the body-site imbalance of the
real data are all preserved. Flipping whole studies also preserves the dependence
between a study's experiments. The experiment-level flip is reported beside it,
because the unit changes the null rather than merely its variance.

Power is measured by injecting a known effect into one trait on the increased side.
The injected counts are taken from the complement of the eight tracked traits -- the
other 309 trait columns the procedures never read -- so each profile's total is
unchanged and every other tracked trait's share is unchanged exactly, which is what
makes the "untouched" truth labels, and therefore the false-discovery proportion,
mean anything.

Acceptance is judged on rejections pooled per procedure against a declared tolerance,
with the simulation replicate as the independent unit. A per-label interval that
merely covers the nominal level is not evidence of control, so the criterion demands
the one-sided upper bound fall below the tolerance, and its own operating
characteristics are reported beside each verdict.

Only the procedures this repository owns are evaluated. The composition and
enrichment arms' native procedures need adapters from their owners, and the
assertion-level urn of #131 is a model question this cannot settle.
"""

