"""Do this repository's directional tests hold their error rates? (#182)

Correct arithmetic and an agreed correction do not make a procedure calibrated. This
module measures what the directional-consistency procedures actually do when their
own nulls are true, following the protocol declared in
``methods/calibration_protocol.json`` before any result was computed.

The null is generated by flipping directions on the real corpus rather than by
simulating counts: for a sampled half of the units, the increased and decreased
labels of every profile in that unit are exchanged. Under each procedure's null the
two sides of a pair are exchangeable, so the flip leaves the distribution unchanged;
and because the counts themselves are untouched, the annotation correlations, the
unequal experiment counts per study, the zeros, and the body-site imbalance of the
real data are all preserved. Flipping whole studies also preserves the dependence
between a study's experiments. The experiment-level flip is reported beside it,
because the unit changes the null rather than merely its variance.

Power is measured by injecting a known effect into one trait for a share of studies,
which also gives the false-discovery proportion among the traits left untouched.

Only the procedures this repository owns are evaluated. The composition and
enrichment arms' native procedures need adapters from their owners, and the
assertion-level urn of #131 is a model question this cannot settle.
"""

from __future__ import annotations

import argparse
import csv
import json
import random
from collections.abc import Callable, Hashable, Mapping, Sequence
from dataclasses import asdict, dataclass, replace
from pathlib import Path

from scipy.stats import binomtest, false_discovery_control

from bsdbng.guild_maps import GuildMatrix, build_matrix, compute_correlation
from bsdbng.paths import DERIVED_DATA_DIR, REPO_ROOT
from bsdbng.table1_trait_maps import compute_direction_shifts
from bsdbng.trait_composition import compute_log_ratio_shifts
from bsdbng.trait_guilds import (
    DEFAULT_EXPERIMENTS_PATH,
    DEFAULT_FULL_DUMP_PATH,
    DEFAULT_PROFILE_PATH,
    OXYGEN_GUILDS,
    TABLE1_TRAITS,
    Profile,
    load_profiles,
    read_bugsigdb_vintage,
    write_stats_report,
)

PROTOCOL_PATH = REPO_ROOT / "methods" / "calibration_protocol.json"
DEFAULT_OUTPUT_DIR = DERIVED_DATA_DIR / "calibration"
VERSION = "calibration-v1"

ALPHA = 0.05
Q_THRESHOLD = 0.05
SEED = 182
REPORT_REPLICATES = 200
#: How many traits the screened procedure selects inside each replicate.
SCREEN_KEEP = 3
#: The traits and studies the injected-signal scenario touches.
INJECTED_TRAIT = "coccus_shaped"
#: A curve rather than one size: a small lift moves almost no study signs, so a
#: single multiplier says little about where these tests start to detect an effect.
INJECTION_MULTIPLIERS = (1.1, 1.3, 2.0, 4.0)
INJECTION_STUDY_SHARE = 0.5


@dataclass(frozen=True)
class Outcome:
    """One procedure's result for one label in one replicate."""

    procedure: str
    label: str
    p_value: float | None
    q_value: float | None
    selected: bool = True


Procedure = Callable[[Sequence[Profile]], list[Outcome]]


def fraction_sign_test(profiles: Sequence[Profile]) -> list[Outcome]:
    """The six Table 1 traits' study sign test, corrected together."""
    result = compute_direction_shifts(list(profiles))
    return [
        Outcome("fraction_sign_test", shift.trait, shift.p_value, shift.q_value)
        for shift in result.shifts
    ]


def screened_fraction_sign_test(profiles: Sequence[Profile]) -> list[Outcome]:
    """Keep the traits furthest from an even split, then correct over those only.

    The published six traits were chosen on this same corpus by another arm's
    criteria. This stands in for that step to measure what selecting on the data and
    then testing the selection does to the error rate; selecting from six rather than
    from hundreds makes the measured inflation a lower bound.
    """
    result = compute_direction_shifts(list(profiles))
    ranked = sorted(
        result.shifts,
        key=lambda s: abs((s.share_up if s.share_up is not None else 0.5) - 0.5),
        reverse=True,
    )
    kept = ranked[:SCREEN_KEEP]
    p_values = [shift.p_value if shift.p_value is not None else 1.0 for shift in kept]
    q_values = [float(q) for q in false_discovery_control(p_values, method="bh")]
    chosen = {shift.trait for shift in kept}
    return [
        Outcome(
            "screened_fraction_sign_test",
            shift.trait,
            shift.p_value,
            q_values[index] if shift.p_value is not None else None,
            selected=True,
        )
        for index, shift in enumerate(kept)
    ] + [
        Outcome("screened_fraction_sign_test", shift.trait, None, None, selected=False)
        for shift in result.shifts
        if shift.trait not in chosen
    ]


def log_ratio_sign_test(profiles: Sequence[Profile]) -> list[Outcome]:
    """The 15 paired log-ratio sign tests, corrected together."""
    result = compute_log_ratio_shifts(list(profiles))
    return [
        Outcome(
            "log_ratio_sign_test",
            f"{summary.numerator}/{summary.reference}",
            summary.sign_p,
            summary.by_q,
        )
        for summary in result.summaries
    ]


def guild_mcnemar_with(matrix: GuildMatrix) -> Procedure:
    """The single exact McNemar on paired aerobe and anaerobe study signs.

    ``compute_correlation`` also returns rank correlations, which need a matrix it
    does not otherwise use for the McNemar; one built from the untransformed corpus
    is passed and those correlations are ignored here.
    """

    def procedure(profiles: Sequence[Profile]) -> list[Outcome]:
        correlation = compute_correlation(list(profiles), matrix)
        return [
            Outcome(
                "guild_mcnemar", "aerobe_vs_anaerobe", correlation.mcnemar_p, correlation.mcnemar_p
            )
        ]

    return procedure


def procedures_for(matrix: GuildMatrix) -> dict[str, Procedure]:
    """Every procedure this module calibrates."""
    return {
        "fraction_sign_test": fraction_sign_test,
        "log_ratio_sign_test": log_ratio_sign_test,
        "guild_mcnemar": guild_mcnemar_with(matrix),
        "screened_fraction_sign_test": screened_fraction_sign_test,
    }


def flip_directions(
    profiles: Sequence[Profile], rng: random.Random, *, unit: str = "study"
) -> list[Profile]:
    """Exchange the two direction labels within a random half of the units.

    ``unit`` is ``study`` or ``experiment``. Every profile of a flipped unit is
    relabelled, so the corpus stays paired and each unit keeps its own counts.
    """
    if unit not in ("study", "experiment"):
        raise ValueError(f"unknown flip unit {unit!r}")
    keys: set[Hashable] = (
        {p.study_id for p in profiles}
        if unit == "study"
        else {(p.study_id, p.experiment_id) for p in profiles}
    )
    flipped = {key for key in sorted(keys, key=repr) if rng.random() < 0.5}
    swap = {"inc": "dec", "dec": "inc"}
    result = []
    for profile in profiles:
        key = profile.study_id if unit == "study" else (profile.study_id, profile.experiment_id)
        result.append(
            replace(profile, inc_dec=swap[profile.inc_dec]) if key in flipped else profile
        )
    return result


def inject_effect(
    profiles: Sequence[Profile],
    rng: random.Random,
    *,
    trait: str = INJECTED_TRAIT,
    multiplier: float,
    study_share: float = INJECTION_STUDY_SHARE,
) -> list[Profile]:
    """Raise one trait's counts on the increased side for a share of studies.

    The profile's total moves with the counts, so the other traits' shares stay
    coherent rather than being rescaled behind the injected one.
    """
    studies = sorted({p.study_id for p in profiles})
    chosen = {study for study in studies if rng.random() < study_share}
    result = []
    for profile in profiles:
        count = profile.guild_counts.get(trait, 0)
        if profile.study_id not in chosen or profile.inc_dec != "inc" or count <= 0:
            result.append(profile)
            continue
        raised = round(count * multiplier)
        counts = dict(profile.guild_counts)
        counts[trait] = raised
        result.append(replace(profile, guild_counts=counts, total=profile.total + raised - count))
    return result


@dataclass(frozen=True)
class Scenario:
    """One way of transforming the corpus before the procedures run."""

    name: str
    truth: str
    transform: Callable[[Sequence[Profile], random.Random], list[Profile]]


def _injection(multiplier: float) -> Callable[[Sequence[Profile], random.Random], list[Profile]]:
    def transform(profiles: Sequence[Profile], rng: random.Random) -> list[Profile]:
        return inject_effect(
            flip_directions(profiles, rng, unit="study"), rng, multiplier=multiplier
        )

    return transform


SCENARIOS: tuple[Scenario, ...] = (
    Scenario(
        "complete_null_study_flip",
        "no trait differs between the directions",
        lambda profiles, rng: flip_directions(profiles, rng, unit="study"),
    ),
    Scenario(
        "complete_null_experiment_flip",
        "no trait differs between the directions",
        lambda profiles, rng: flip_directions(profiles, rng, unit="experiment"),
    ),
    *(
        Scenario(
            f"injected_{multiplier:g}x_study_flip",
            f"{INJECTED_TRAIT} raised {multiplier:g}x on the increased side of half the studies",
            _injection(multiplier),
        )
        for multiplier in INJECTION_MULTIPLIERS
    ),
)


def run_replicates(
    profiles: Sequence[Profile],
    scenario: Scenario,
    replicates: int,
    seed: int = SEED,
    procedures: Mapping[str, Procedure] | None = None,
) -> list[list[Outcome]]:
    """Run every procedure on ``replicates`` transformed copies of the corpus."""
    chosen = procedures or {}
    runs: list[list[Outcome]] = []
    for index in range(replicates):
        rng = random.Random(f"{seed}:{scenario.name}:{index}")
        transformed = scenario.transform(profiles, rng)
        outcomes: list[Outcome] = []
        for procedure in chosen.values():
            outcomes.extend(procedure(transformed))
        runs.append(outcomes)
    return runs


def _interval(successes: int, trials: int) -> tuple[float, float]:
    if not trials:
        return (0.0, 1.0)
    interval = binomtest(successes, trials).proportion_ci(confidence_level=0.95, method="exact")
    return float(interval.low), float(interval.high)


def summarize(
    runs: Sequence[Sequence[Outcome]], scenario: Scenario, injected: str | None
) -> list[dict[str, object]]:
    """Per-test rejection rates, family error, and false-discovery proportions."""
    rows: list[dict[str, object]] = []
    procedures = sorted({o.procedure for run in runs for o in run})
    for procedure in procedures:
        labels = sorted({o.label for run in runs for o in run if o.procedure == procedure})
        for label in labels:
            tested = [
                next(
                    (o for o in run if o.procedure == procedure and o.label == label),
                    None,
                )
                for run in runs
            ]
            present = [o for o in tested if o is not None and o.selected and o.p_value is not None]
            rejected_p = sum(1 for o in present if o.p_value is not None and o.p_value <= ALPHA)
            rejected_q = sum(
                1 for o in present if o.q_value is not None and o.q_value <= Q_THRESHOLD
            )
            low, high = _interval(rejected_p, len(present))
            # A ratio naming the injected trait is affected by it too.
            is_injected = injected is not None and injected in str(label).split("/")
            rows.append(
                {
                    "scenario": scenario.name,
                    "truth": scenario.truth,
                    "procedure": procedure,
                    "label": label,
                    "role": "injected_effect" if is_injected else "null",
                    "replicates": len(runs),
                    "replicates_tested": len(present),
                    "rejections_p": rejected_p,
                    "rejection_rate_p": rejected_p / len(present) if present else None,
                    "rejection_rate_p_ci_low": low,
                    "rejection_rate_p_ci_high": high,
                    "rejections_q": rejected_q,
                    "rejection_rate_q": rejected_q / len(present) if present else None,
                    "smallest_attainable_p": min(
                        (o.p_value for o in present if o.p_value is not None), default=None
                    ),
                }
            )
    for procedure in procedures:
        any_rejection = 0
        false_discovery: list[float] = []
        for run in runs:
            calls = [
                o
                for o in run
                if o.procedure == procedure
                and o.selected
                and o.q_value is not None
                and o.q_value <= Q_THRESHOLD
            ]
            any_rejection += bool(calls)
            if calls:
                false = [
                    o for o in calls if injected is None or injected not in str(o.label).split("/")
                ]
                false_discovery.append(len(false) / len(calls))
            else:
                false_discovery.append(0.0)
        low, high = _interval(any_rejection, len(runs))
        rows.append(
            {
                "scenario": scenario.name,
                "truth": scenario.truth,
                "procedure": procedure,
                "label": "FAMILY",
                "role": "family",
                "replicates": len(runs),
                "replicates_tested": len(runs),
                "rejections_p": any_rejection,
                "rejection_rate_p": any_rejection / len(runs) if runs else None,
                "rejection_rate_p_ci_low": low,
                "rejection_rate_p_ci_high": high,
                "rejections_q": any_rejection,
                "rejection_rate_q": any_rejection / len(runs) if runs else None,
                "mean_false_discovery_proportion": (
                    sum(false_discovery) / len(false_discovery) if false_discovery else None
                ),
            }
        )
    return rows


def check_criteria(rows: Sequence[dict[str, object]]) -> list[dict[str, object]]:
    """Judge the declared acceptance criteria, reporting failures as failures."""
    protocol = json.loads(PROTOCOL_PATH.read_text(encoding="utf-8"))
    results: list[dict[str, object]] = []
    null_rows = [r for r in rows if str(r["scenario"]).startswith("complete_null")]
    for criterion in protocol["acceptance_criteria"]:
        for procedure in criterion["applies_to"]:
            subject = [r for r in null_rows if r["procedure"] == procedure]
            verdict, detail = "not_evaluated", ""
            if criterion["id"] == "per_test_level":
                per_test = [r for r in subject if r["role"] == "null" and r["label"] != "FAMILY"]
                worst = max(
                    (r for r in per_test if r["rejection_rate_p_ci_low"] is not None),
                    key=lambda r: float(str(r["rejection_rate_p_ci_low"])),
                    default=None,
                )
                if worst is not None:
                    low = float(str(worst["rejection_rate_p_ci_low"]))
                    verdict = "pass" if low <= ALPHA else "fail"
                    detail = (
                        f"highest lower interval bound {low:.3f} at {worst['label']} "
                        f"({worst['scenario']})"
                    )
            elif criterion["id"] == "family_error":
                families = [r for r in subject if r["role"] == "family"]
                worst_rate = max(
                    (float(str(r["rejection_rate_q"])) for r in families if r["rejection_rate_q"]),
                    default=0.0,
                )
                verdict = "pass" if worst_rate <= 0.10 else "fail"
                detail = f"highest rate of replicates with any q <= {Q_THRESHOLD}: {worst_rate:.3f}"
            elif criterion["id"] == "power_reported":
                powered = [
                    r
                    for r in rows
                    if r["procedure"] == procedure and r["role"] == "injected_effect"
                ]
                verdict = "pass" if powered else "fail"
                detail = "; ".join(
                    f"{r['scenario']}: power {float(str(r['rejection_rate_q'])):.3f}"
                    for r in powered
                    if r["rejection_rate_q"] is not None
                )
            elif criterion["id"] == "selection_inflation_measured":
                per_test = [r for r in subject if r["role"] == "null" and r["label"] != "FAMILY"]
                rates = [
                    float(str(r["rejection_rate_p"]))
                    for r in per_test
                    if r["rejection_rate_p"] is not None
                ]
                verdict = "reported"
                detail = (
                    f"per-test rejection rate under the null between {min(rates):.3f} and "
                    f"{max(rates):.3f}"
                    if rates
                    else "no selected tests"
                )
            results.append(
                {
                    "criterion": criterion["id"],
                    "procedure": procedure,
                    "requirement": criterion["criterion"],
                    "verdict": verdict,
                    "detail": detail,
                }
            )
    return results


def _format(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:.6g}"
    return str(value)


def _write(path: Path, rows: Sequence[dict[str, object]]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields: list[str] = []
    for row in rows:
        for key in row:
            if key not in fields:
                fields.append(key)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t", lineterminator="\n")
        writer.writerow(fields)
        writer.writerows([_format(row.get(field)) for field in fields] for row in rows)
    return path


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile-input", type=Path, default=DEFAULT_PROFILE_PATH)
    parser.add_argument("--experiments-input", type=Path, default=DEFAULT_EXPERIMENTS_PATH)
    parser.add_argument("--full-dump-input", type=Path, default=DEFAULT_FULL_DUMP_PATH)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--replicates", type=int, default=REPORT_REPLICATES)
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--code-commit", help="Source revision, supplied by the Justfile recipe")
    args = parser.parse_args(argv)

    guilds = {**TABLE1_TRAITS, **OXYGEN_GUILDS}
    profiles, stats = load_profiles(
        args.profile_input, args.experiments_input, guilds, reject_missing_counts=True
    )
    vintage = read_bugsigdb_vintage(args.full_dump_input)
    write_stats_report(stats, vintage)

    rows: list[dict[str, object]] = []
    matrix = build_matrix(profiles, max_conditions=60, max_body_sites=8, min_studies=3)
    procedures = procedures_for(matrix)
    for scenario in SCENARIOS:
        runs = run_replicates(profiles, scenario, args.replicates, args.seed, procedures)
        injected = INJECTED_TRAIT if scenario.name.startswith("injected") else None
        rows.extend(summarize(runs, scenario, injected))
        print(f"{scenario.name}: {args.replicates} replicates")
    criteria = check_criteria(rows)

    output = args.output_dir
    written = [
        _write(output / "calibration_results.tsv", rows),
        _write(output / "calibration_criteria.tsv", criteria),
    ]
    status = {
        "version": VERSION,
        "protocol": str(PROTOCOL_PATH.relative_to(REPO_ROOT)),
        "bugsigdb_vintage": vintage,
        "code_commit": args.code_commit,
        "seed": args.seed,
        "replicates": args.replicates,
        "corpus": asdict(stats),
        "procedures": {
            "fraction_sign_test": {
                "tested_level": "study",
                "family": "Benjamini-Hochberg over six Table 1 traits",
            },
            "log_ratio_sign_test": {
                "tested_level": "study",
                "family": "Benjamini-Yekutieli over 15 trait pairs",
            },
            "guild_mcnemar": {"tested_level": "study", "family": "single test"},
            "screened_fraction_sign_test": {
                "tested_level": "study",
                "family": f"Benjamini-Hochberg over {SCREEN_KEEP} traits selected in the replicate",
            },
        },
        "calibration_status": {
            row["procedure"]: row["verdict"]
            for row in criteria
            if row["criterion"] in ("per_test_level", "selection_inflation_measured")
        },
        "not_calibrated_here": [
            "the enrichment arm's hypergeometric urn (#131)",
            "the composition arm's native transformed test",
            "the aggregated profile-support rule (#177)",
        ],
    }
    status_path = output / "calibration_status.json"
    status_path.write_text(json.dumps(status, indent=2) + "\n", encoding="utf-8")
    written.append(status_path)
    for row in criteria:
        print(f"  {row['criterion']:32} {row['procedure']:28} {row['verdict']:12} {row['detail']}")
    for path in written:
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
