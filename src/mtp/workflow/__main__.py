"""Public commands for the tracked raw-to-core workflow (#629)."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from mtp.paths import REPO_ROOT
from mtp.workflow.comparison import compare_legacy_bundle
from mtp.workflow.consumers import import_legacy_provenance, verify_consumer_record
from mtp.workflow.definition import read_definition
from mtp.workflow.operations import OPERATIONS, trace_profile_feature, validate_core_product
from mtp.workflow.runtime import artifact_path, execute_workflow
from mtp.workflow.verification import verify_core_run

DEFAULT_SPEC = REPO_ROOT / "workflows" / "bugsigdb_core.yaml"


def _bindings(values: list[str]) -> dict[str, str]:
    result: dict[str, str] = {}
    for value in values:
        key, separator, item = value.partition("=")
        if not separator or not key or not item or key in result:
            raise ValueError(f"Expected a unique NAME=VALUE binding: {value!r}")
        result[key] = item
    return result


def describe(spec_path: Path) -> str:
    """Render product and stage tables directly from the authoritative specification."""
    spec = read_definition(spec_path)
    lines = [
        f"# {spec.id} ({spec.version})",
        "",
        "Generated by `just workflow-describe`; edit the specification, then regenerate.",
        "",
        "| Product | Kind | Unit | Cohort | File or collection |",
        "| --- | --- | --- | --- | --- |",
    ]
    for product in spec.products:
        lines.append(
            f"| `{product.id}` | {product.kind} | {product.unit or 'not applicable'} | "
            f"{product.cohort or 'not applicable'} | `{product.filename}` |"
        )
    lines.extend(["", "| Step | Operation | Inputs | Outputs |", "| --- | --- | --- | --- |"])
    for step in spec.steps:
        lines.append(
            f"| {step.id} | `{step.operation}` | {', '.join(step.inputs)} | "
            f"{', '.join(step.outputs)} |"
        )
    return "\n".join(lines) + "\n"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    check = sub.add_parser("check", help="Validate schema and DAG references")
    check.add_argument("spec", type=Path, nargs="?", default=DEFAULT_SPEC)
    documentation = sub.add_parser("describe", help="Generate product/stage documentation")
    documentation.add_argument("spec", type=Path, nargs="?", default=DEFAULT_SPEC)
    run = sub.add_parser("run", help="Execute registered Python operations from the specification")
    run.add_argument("spec", type=Path, nargs="?", default=DEFAULT_SPEC)
    run.add_argument("--input", action="append", default=[], metavar="PRODUCT=PATH")
    run.add_argument("--parameter", action="append", default=[], metavar="NAME=VALUE")
    run.add_argument("--output-root", type=Path, required=True)
    fixture = sub.add_parser("fixture", help="Run the small offline fixture from raw inputs")
    fixture.add_argument("--output-root", type=Path, required=True)
    validate = sub.add_parser("validate", help="Recheck execution records and actual artifacts")
    validate.add_argument("manifest", type=Path)
    lineage = sub.add_parser("lineage", help="Trace a product, optionally a profile/trait cell")
    lineage.add_argument("manifest", type=Path)
    lineage.add_argument("product")
    lineage.add_argument("--profile", nargs=3, metavar=("STUDY", "EXPERIMENT", "DIRECTION"))
    lineage.add_argument(
        "--feature", help="Qualified feature ID, preserving predicate where present"
    )
    legacy = sub.add_parser("import-legacy", help="Preserve old claims as explicitly unverified")
    legacy.add_argument("source", type=Path)
    legacy.add_argument("output", type=Path)
    consumer = sub.add_parser(
        "verify-consumer", help="Verify downstream outputs and their core run"
    )
    consumer.add_argument("record", type=Path)
    compare = sub.add_parser("compare-legacy", help="Compare rebuilt numeric tables by IDs")
    compare.add_argument("manifest", type=Path)
    compare.add_argument("baseline_dir", type=Path)
    compare.add_argument("output", type=Path)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.command == "check":
        spec = read_definition(args.spec)
        unknown = {step.operation for step in spec.steps} - OPERATIONS.keys()
        if unknown:
            raise ValueError(f"Unregistered operations: {sorted(unknown)}")
        print(f"Validated {spec.id}: {len(spec.steps)} steps, {len(spec.products)} products")
    elif args.command == "describe":
        print(describe(args.spec), end="")
    elif args.command in {"run", "fixture"}:
        if args.command == "fixture":
            source = REPO_ROOT / "tests" / "fixtures" / "workflow"
            inputs = {
                "raw_dump": source / "full_dump.csv",
                "kg_edges": source / "merged-kg_edges.tsv",
                "kg_nodes": source / "merged-kg_nodes.tsv",
            }
            spec_path, parameters = DEFAULT_SPEC, {"source_mode": "fixture"}
        else:
            inputs = {key: Path(value) for key, value in _bindings(args.input).items()}
            spec_path, parameters = args.spec, _bindings(args.parameter)
        run = execute_workflow(
            spec_path,
            inputs,
            args.output_root,
            OPERATIONS,
            parameter_overrides=parameters,
            validator=validate_core_product,
            repository_root=REPO_ROOT,
        )
        print(run.manifest_path)
    elif args.command in {"validate", "lineage"}:
        run = verify_core_run(args.manifest)
        paths = {
            artifact.product_id: artifact_path(run, artifact.product_id)
            for artifact in run.artifacts or []
        }
        if args.command == "validate":
            print(f"Verified {run.run_id}: bytes, execution graph, and scientific contracts")
        elif args.profile is not None or args.feature is not None:
            if args.profile is None or args.feature is None:
                parser.error("Cell lineage requires both --profile and --feature")
            if args.product not in {"count_profiles", "ora_profiles"}:
                parser.error("Cell lineage requires count_profiles or ora_profiles")
            cohort = next(
                artifact.cohort
                for artifact in run.artifacts or []
                if artifact.product_id == args.product
            )
            result = trace_profile_feature(
                paths["studies"],
                paths["taxa_matrix"],
                paths["kg_edges"],
                paths["kg_nodes"],
                (args.profile[0], args.profile[1], args.profile[2]),
                args.feature,
                host_species=None if cohort == "all" else cohort,
            )
            print(json.dumps(result, indent=2))
        else:
            artifact_path(run, args.product)
            products = {product.id: product for product in run.definition.products}
            producers = {product: step for step in run.definition.steps for product in step.outputs}
            visited: set[str] = set()
            pending = [args.product]
            while pending:
                product_id = pending.pop()
                if product_id in visited:
                    continue
                visited.add(product_id)
                if not products[product_id].external:
                    pending.extend(producers[product_id].inputs)
            print(
                json.dumps(
                    {
                        "run_id": run.run_id,
                        "product": args.product,
                        "artifacts": [
                            artifact.model_dump(mode="json")
                            for artifact in run.artifacts or []
                            if artifact.product_id in visited
                        ],
                    },
                    indent=2,
                )
            )
    elif args.command == "import-legacy":
        print(import_legacy_provenance(args.source, args.output))
    elif args.command == "verify-consumer":
        print(verify_consumer_record(args.record).id)
    elif args.command == "compare-legacy":
        print(compare_legacy_bundle(args.manifest, args.baseline_dir, args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
